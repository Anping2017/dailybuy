// 过滤掉引用不存在食材的菜
const ingredients = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'data', 'ingredients.json'), 'utf8'));
const validIngredientIds = new Set(ingredients.map(i => i.id));
const skipped = [];
const validRecipes = NEW.filter(r => {
  const invalid = r.ingredients.filter(ri => !validIngredientIds.has(ri.ingredientId));
  if (invalid.length > 0) {
    skipped.push({ name: r.nameZh, missing: invalid.map(i => i.ingredientId) });
    return false;
  }
  return true;
});

if (skipped.length > 0) {
  console.log(`⚠ 跳过 ${skipped.length} 道菜(引用不存在食材):`);
  skipped.forEach(s => console.log(`  ${s.name}: 缺 [${s.missing.join(', ')}]`));
}

const existingIds = new Set(recipes.map(r => r.id));
const toAdd = validRecipes.filter(r => {
  if (existingIds.has(r.id)) {
    console.log(`⚠ 跳过已存在: ${r.id}`);
    return false;
  }
  return true;
});

console.log(`\n新增 ${toAdd.length} 道菜`);

if (process.argv.includes('--write')) {
  recipes.push(...toAdd);
  fs.writeFileSync(RECIPES_PATH, JSON.stringify(recipes, null, 2));
  console.log(`✓ 写入(总数 ${recipes.length})`);
} else {
  console.log('(dry-run)');
  console.log('示例:');
  toAdd.slice(0, 10).forEach(r => console.log(`  + ${r.nameZh} [${r.regionalCuisine}/${r.cookingMethod}]`));
}
